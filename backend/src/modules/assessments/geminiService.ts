import { IAIAssessment, IAnomaly, IEvidence } from '../../shared/types';
import { EvidenceService } from '../evidence/evidenceService';
import { SatelliteService } from '../satellites/satelliteService';
import { SpaceWeatherService } from '../space-weather/spaceWeatherService';
import { IAIAssessmentRepository } from '../../repositories/interfaces/IAIAssessmentRepository';
import { getAIAssessmentRepository } from '../../repositories';
import { config } from '../../config';
import { logger } from '../../shared/logger';

const assessmentCache = new Map<string, IAIAssessment>();

export class GeminiService {
  private static repository: IAIAssessmentRepository | null = null;

  private static getRepo(): IAIAssessmentRepository {
    return this.repository || getAIAssessmentRepository();
  }

  public static setRepository(repo: IAIAssessmentRepository): void {
    this.repository = repo;
    assessmentCache.clear();
  }

  public static async assessAnomaly(anomaly: IAnomaly): Promise<IAIAssessment> {
    // 1. Check if already in-memory cache
    if (assessmentCache.has(anomaly.anomalyId)) {
      return assessmentCache.get(anomaly.anomalyId)!;
    }

    // 2. Check if already stored in repository
    try {
      const stored = await this.getRepo().findByAnomalyId(anomaly.anomalyId);
      if (stored) {
        assessmentCache.set(anomaly.anomalyId, stored);
        return stored;
      }
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Unknown error';
      logger.warn(`Failed to query assessment repository for ${anomaly.anomalyId}`, { error: message });
    }

    // 3. Correlate with external context (NOAA, DONKI, SAA orbit, coupled subsystems)
    try {
      const { CorrelationEngine } = await import('../correlation/correlationEngine');
      await CorrelationEngine.correlateAnomaly(anomaly);
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Unknown correlation error';
      logger.debug('Context correlation before assessment skipped/failed', { error: msg });
    }

    const requestedAt = new Date();
    const evidenceItems = await EvidenceService.getEvidenceForIds(anomaly.evidenceIds);
    const satellite = await SatelliteService.getSatelliteById(anomaly.satelliteId);
    const spaceWeather = await SpaceWeatherService.getSpaceWeather();

    let assessment: IAIAssessment;
    const isTest = process.env.NODE_ENV === 'test' || process.env.JEST_WORKER_ID !== undefined;

    if (config.gemini.apiKey && !isTest) {
      try {
        assessment = await this.callGeminiAPI(anomaly, evidenceItems, satellite, spaceWeather, requestedAt);
      } catch (err) {
        logger.warn('Gemini API call failed, falling back to deterministic evidence reasoning', { error: err });
        assessment = this.generateFallbackAssessment(
          anomaly,
          evidenceItems,
          requestedAt,
          'Gemini API call failed, generated by SpaceGuard Grounded Fallback Engine'
        );
      }
    } else {
      assessment = this.generateFallbackAssessment(
        anomaly,
        evidenceItems,
        requestedAt,
        'Offline mode (GEMINI_API_KEY not configured)'
      );
    }

    assessmentCache.set(anomaly.anomalyId, assessment);

    // 3. Persist structured assessment to database
    try {
      await this.getRepo().create(assessment);
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Unknown write error';
      logger.warn(`Failed to persist assessment for anomaly ${anomaly.anomalyId}`, { error: message });
    }

    return assessment;
  }

  public static async getAssessmentForAnomaly(anomalyId: string): Promise<IAIAssessment | null> {
    const cached = assessmentCache.get(anomalyId);
    if (cached) return cached;

    try {
      const stored = await this.getRepo().findByAnomalyId(anomalyId);
      if (stored) {
        assessmentCache.set(anomalyId, stored);
        return stored;
      }
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : 'Unknown error';
      logger.warn(`Failed to fetch assessment for ${anomalyId}`, { error: message });
    }

    return null;
  }

  private static async callGeminiAPI(
    anomaly: IAnomaly,
    evidenceItems: IEvidence[],
    satellite: unknown,
    spaceWeather: unknown,
    requestedAt: Date
  ): Promise<IAIAssessment> {
    const evidenceListPrompt = evidenceItems
      .map((e) => `[${e.evidenceId}] Source: ${e.source} | Description: ${e.description}`)
      .join('\n');

    const prompt = `You are SpaceGuard AI, an evidence-grounded spacecraft diagnostics engine.
Your task is to analyze an anomaly detected on satellite ${anomaly.satelliteId}.

MANDATORY RULES:
1. Every claim in evidenceClaims MUST cite valid evidence IDs from the provided evidence list.
2. DO NOT invent new evidence IDs, telemetry readings, or environmental events.
3. Be completely transparent about what is known, unknown, and cannot be determined.
4. Output strictly valid JSON matching the specified schema.

CONTEXT:
Satellite: ${JSON.stringify(satellite)}
Space Weather: ${JSON.stringify(spaceWeather)}
Anomaly Record:
- ID: ${anomaly.anomalyId}
- Parameter: ${anomaly.parameter} (${anomaly.subsystem})
- Observed Value: ${anomaly.value} ${anomaly.unit} (baseline: ${anomaly.baseline})
- Severity: ${anomaly.severity}
- Detection Method: ${anomaly.detectionMethod}
- Anomaly Score: ${anomaly.anomalyScore}

AVAILABLE EVIDENCE:
${evidenceListPrompt}

RESPOND STRICTLY WITH A JSON OBJECT adhering to this schema:
{
  "priority": "low" | "medium" | "high" | "critical",
  "summary": "one sentence summary of the operational event",
  "evidenceClaims": [
    {
      "claim": "Specific factual claim directly supported by evidence",
      "evidenceIds": ["EVID-..."]
    }
  ],
  "interpretation": "Detailed engineering interpretation explaining the physical subsystem dynamics",
  "possibleCauses": ["Cause 1", "Cause 2"],
  "known": ["Firmly established fact based on telemetry"],
  "unknown": ["Aspect that cannot be confirmed with current telemetry"],
  "cannotDetermine": ["Question that requires ground testing or additional instrumentation"],
  "uncertainty": "Explicit statement of diagnostic uncertainty",
  "recommendedInvestigation": ["Actionable next step 1", "Actionable next step 2"]
}`;

    const url = `https://generativelanguage.googleapis.com/v1beta/models/${config.gemini.model}:generateContent?key=${config.gemini.apiKey}`;

    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: {
          responseMimeType: 'application/json',
          temperature: 0.2,
        },
      }),
      signal: AbortSignal.timeout(15000),
    });

    if (!response.ok) {
      throw new Error(`Gemini API returned status ${response.status}`);
    }

    const result = (await response.json()) as {
      candidates?: Array<{ content?: { parts?: Array<{ text?: string }> } }>;
    };

    const text = result.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!text) {
      throw new Error('Gemini API returned empty response');
    }

    const parsed = JSON.parse(text);
    const respondedAt = new Date();

    return {
      assessmentId: `ASSESS-${anomaly.anomalyId}`,
      anomalyId: anomaly.anomalyId,
      satelliteId: anomaly.satelliteId,
      priority: parsed.priority || anomaly.severity,
      summary: parsed.summary || `Investigation assessment for ${anomaly.parameter} anomaly`,
      evidenceClaims: parsed.evidenceClaims || [],
      interpretation: parsed.interpretation || anomaly.description,
      possibleCauses: parsed.possibleCauses || [],
      known: parsed.known || [],
      unknown: parsed.unknown || [],
      cannotDetermine: parsed.cannotDetermine || [],
      uncertainty: parsed.uncertainty || 'Assessment grounded solely in received telemetry evidence.',
      recommendedInvestigation: parsed.recommendedInvestigation || [],
      modelUsed: config.gemini.model,
      promptVersion: 'v1.0.0',
      requestedAt,
      respondedAt,
      latencyMs: respondedAt.getTime() - requestedAt.getTime(),
      status: 'success',
    };
  }

  // Deterministic grounded reasoning fallback guaranteeing 100% reliability and zero hallucinations
  private static generateFallbackAssessment(
    anomaly: IAnomaly,
    evidenceItems: IEvidence[],
    requestedAt: Date,
    statusNote: string
  ): IAIAssessment {
    const validEvidenceIds = evidenceItems.map((e) => e.evidenceId);
    const respondedAt = new Date();

    const claims = [
      {
        claim: `Telemetry parameter ${anomaly.parameter} was recorded at ${anomaly.value.toFixed(2)}${anomaly.unit} against nominal baseline of ${anomaly.baseline.toFixed(2)}${anomaly.unit}.`,
        evidenceIds: validEvidenceIds.slice(0, 1),
      },
    ];

    if (validEvidenceIds.length > 1) {
      claims.push({
        claim: `Multi-detector verification flagged anomaly via ${anomaly.detectionMethod} engine with confidence score ${anomaly.anomalyScore.toFixed(2)}.`,
        evidenceIds: validEvidenceIds.slice(1, 2),
      });
    }

    const envOrOrbitalEvidence = evidenceItems.filter((e) => e.source === 'environment' || e.source === 'orbit');
    for (const ev of envOrOrbitalEvidence) {
      claims.push({
        claim: `External context correlation: ${ev.description} (Temporal/environmental correlation reported; does not establish causation).`,
        evidenceIds: [ev.evidenceId],
      });
    }

    let interpretation = `The ${anomaly.subsystem} subsystem exhibited anomalous deviation in ${anomaly.parameter}.`;
    const possibleCauses: string[] = [];
    const recommendedInvestigation: string[] = [];

    if (anomaly.subsystem === 'thermal') {
      interpretation +=
        ' Extreme thermal excursions can lead to thermal stress on integrated circuitry and payload sensors.';
      possibleCauses.push('Thermal radiator obstruction or orientation misalignment');
      possibleCauses.push('Internal heat pipe failure or local high-dissipation circuit fault');
      possibleCauses.push('Solar aspect angle shift or unexpected eclipse exit profile');
      recommendedInvestigation.push('Inspect sun vector and solar panel tilt orientation history');
      recommendedInvestigation.push('Verify heater control telemetry and thermistor continuity');
      recommendedInvestigation.push('Cross-reference space weather solar proton flux data');
    } else if (anomaly.subsystem === 'power') {
      interpretation += ' Power bus instability threatens telemetry link and attitude stability.';
      possibleCauses.push('Secondary battery cell degradation or short circuit');
      possibleCauses.push('Excessive parasitic payload load consumption');
      possibleCauses.push('Solar array shunting regulator malfunction');
      recommendedInvestigation.push('Review power budget allocation and turn off non-essential payloads');
      recommendedInvestigation.push('Analyze battery state-of-charge discharge curve');
      recommendedInvestigation.push('Check solar panel I-V characteristic telemetry');
    } else if (anomaly.subsystem === 'communication') {
      interpretation += ' Transceiver link degradation risks telemetry downlink blackout.';
      possibleCauses.push('Ground station antenna pointing misalignment');
      possibleCauses.push('Local RF interference or transponder amplifier degradation');
      possibleCauses.push('Atmospheric or ionospheric scintillation');
      recommendedInvestigation.push('Schedule pass over secondary ground station');
      recommendedInvestigation.push('Verify transponder transmit power and receiver AGC levels');
    } else {
      possibleCauses.push(`Subsystem component anomaly in ${anomaly.parameter}`);
      possibleCauses.push('Sensor calibration drift or intermittent bus harness connection');
      recommendedInvestigation.push('Correlate orbital position with sensor field of view');
      recommendedInvestigation.push('Check telemetry packet checksum error counters');
    }

    return {
      assessmentId: `ASSESS-${anomaly.anomalyId}`,
      anomalyId: anomaly.anomalyId,
      satelliteId: anomaly.satelliteId,
      priority: anomaly.severity,
      summary: `${anomaly.severity.toUpperCase()} operational alert: ${anomaly.parameter} anomalous deviation on ${anomaly.satelliteId}.`,
      evidenceClaims: claims,
      interpretation,
      possibleCauses,
      known: [
        `Parameter ${anomaly.parameter} current value is ${anomaly.value.toFixed(2)}${anomaly.unit}`,
        `Baseline expected value is ${anomaly.baseline.toFixed(2)}${anomaly.unit}`,
        `Detection validated via ${anomaly.detectionMethod} method`,
      ],
      unknown: [
        'Transient vs permanent component degradation status cannot be confirmed without prolonged telemetry monitoring',
      ],
      cannotDetermine: [
        'Root physical cause cannot be diagnosed without commanded diagnostic telemetry pass',
      ],
      uncertainty: `Confidence strictly bounded by ${validEvidenceIds.length} telemetry/detection evidence points. ${statusNote}.`,
      recommendedInvestigation,
      modelUsed: 'spaceguard-rule-grounded-fallback',
      promptVersion: 'v1.0.0',
      requestedAt,
      respondedAt,
      latencyMs: respondedAt.getTime() - requestedAt.getTime(),
      status: 'success',
    };
  }

  public static clearCache(): void {
    assessmentCache.clear();
  }
}
